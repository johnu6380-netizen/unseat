// lib/calendar/buildEventDescription.ts
// Pure function — no imports, no DB, no side effects.
//
// Takes a flat list of exercises (resolved from WorkSession.exerciseIds)
// and groups them into STRETCH (INHIBIT + LENGTHEN) and
// STRENGTHEN (ACTIVATE + INTEGRATE) for the calendar event body.

type Exercise = {
  name: string;
  phaseType: string;
  videoUrl?: string | null;
};

const STRETCH_PHASES = new Set(["INHIBIT", "LENGTHEN"]);
const STRENGTHEN_PHASES = new Set(["ACTIVATE", "INTEGRATE"]);

export function buildEventDescription(params: {
  message: string;
  durationMins: number;
  exercises: Exercise[];
}): string {
  const { message, durationMins, exercises } = params;

  const lines: string[] = [];

  lines.push(message);
  lines.push("");
  lines.push(`Duration: ${durationMins} minutes`);
  lines.push("");
  lines.push("---------------------");

  const stretchExercises = exercises.filter((ex) =>
    STRETCH_PHASES.has(ex.phaseType)
  );
  const strengthenExercises = exercises.filter((ex) =>
    STRENGTHEN_PHASES.has(ex.phaseType)
  );

  if (stretchExercises.length > 0) {
    lines.push("");
    lines.push("STRETCH");
    for (const ex of stretchExercises) {
      lines.push(`  * ${ex.name}`);
      if (ex.videoUrl) {
        lines.push(`    Instructions: ${ex.videoUrl}`);
      }
    }
  }

  if (strengthenExercises.length > 0) {
    lines.push("");
    lines.push("STRENGTHEN");
    for (const ex of strengthenExercises) {
      lines.push(`  * ${ex.name}`);
      if (ex.videoUrl) {
        lines.push(`    Instructions: ${ex.videoUrl}`);
      }
    }
  }

  lines.push("");
  lines.push("---------------------");
  lines.push("Generated by Unseat · unseat.app");

  return lines.join("\n");
}
